// 지역명을 검색어로 쓸 때 접미사(시/군/구)를 뗀 짧은 형태로 바꾼다 — 게시글 위치는
// 카카오맵에서 온 자유 텍스트라 "강릉시"가 아니라 "강릉"처럼 짧게 저장돼 있을 가능성이 높아서다
// (festival 도메인의 toShortRegionName과 동일한 규칙: 복합명은 그대로, 짧아지면 안 되는 것도 그대로).
export function toRegionSearchTerm(name) {
  if (name.includes(' ')) return name;
  if (name === '세종특별자치시') return '세종';
  const match = name.match(/^(.{2,})(시|군|구)$/);
  return match ? match[1] : name;
}
